"""Manual, non-production private Telegram runner with secure credential file.

DEFAULT: validates isolated credentials and recipient geometry but NO HTTP.
Opt-in --send-fixed-test requires two explicit switches plus the exact
approval phrase, then can send ONE fixed DO NOT TRADE text to a personal
PRIVATE chat using a distinct test bot. No trading levels, signals, pipeline,
private outbox, scheduler, production writes or automated retries.

Secret JSON must be owner-only 0600 under an owner-only private directory,
not in Git, stdout, environment variables or command-line arguments.
Do NOT invoke without a separately verified private test bot/chat and a
user-authorized real test message. The test file is not generated by code.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import stat
import time

from services.t7sonic.forward_private_telegram import (
    APPROVAL_PHRASE, PrivateTestConsent,
    validate_private_test_consent,
    optional_private_telegram_connectivity_test,
)

REQUIRED_SECRET_KEYS = frozenset({
    "test_bot_token", "production_bot_token",
    "private_test_chat_id", "production_chat_id",
})
MAX_CONFIG_BYTES = 2048


def read_private_config(path: str) -> dict:
    """Read one preexisting owner-only JSON; reject symlinks & shared paths."""
    if not isinstance(path, str):
        raise PermissionError("Private absolute credential filename required")
    target=Path(path)
    if (not target.is_absolute() or target.is_symlink() or
            not target.parent.is_dir() or target.parent.is_symlink()):
        raise PermissionError("Real absolute secret file in private directory only")
    parent=target.parent.stat()
    if (parent.st_uid != os.getuid() or
            not stat.S_ISDIR(parent.st_mode) or
            parent.st_mode & 0o077):
        raise PermissionError("Secret file parent must be owner-only")
    descriptor=os.open(
        target,os.O_RDONLY|getattr(os,"O_NOFOLLOW",0)
    )
    try:
        info=os.fstat(descriptor)
        if (not stat.S_ISREG(info.st_mode) or
                info.st_uid != os.getuid() or
                info.st_mode & 0o077 or
                not 2 <= info.st_size <= MAX_CONFIG_BYTES):
            raise PermissionError("Credential file must be private and bounded")
        with os.fdopen(descriptor,"rb",closefd=False) as stream:
            raw=stream.read(MAX_CONFIG_BYTES+1)
        if len(raw)>MAX_CONFIG_BYTES:
            raise PermissionError("Credential file too large")
    finally:
        os.close(descriptor)
    try:
        config=json.loads(raw)
    except (UnicodeDecodeError,ValueError) as exc:
        raise ValueError("Invalid private credential JSON") from None
    if not isinstance(config,dict) or set(config)!=REQUIRED_SECRET_KEYS or any(
        not isinstance(value,str) for value in config.values()
    ):
        raise ValueError("Unexpected private Telegram credential schema")
    return config


def validate_preflight(config: dict, *, now: int) -> dict:
    if not isinstance(config,dict):
        raise PermissionError("Private configuration required")
    test=PrivateTestConsent(
        **config,
        authorization_phrase=APPROVAL_PHRASE,
        approved_until_unix_s=now+90,
    )
    validate_private_test_consent(test,now_unix_s=now)
    return {
        "status":"PRIVATE_TEST_CONFIG_VALIDATED_NO_NETWORK",
        "dedicated_test_bot_distinct_from_production":True,
        "positive_one_to_one_test_chat_id_format":True,
        "production_chat_differs_from_test_chat":True,
        "provider_chat_type_checked_live":False,
        "network_contacted":False,
        "telegram_messages_sent":0,
        "test_message_delivery_verified":False,
        "client_publication_authorized":False,
    }


def run_manual(args: argparse.Namespace) -> dict:
    """No automatic network, no retry, no raw secret return."""
    config=read_private_config(args.config)
    now=int(time.time())
    preliminary=validate_preflight(config,now=now)
    if not args.send_fixed_test:
        if args.network_approved or args.second_confirmation or args.approval_phrase:
            raise PermissionError("Approval flags without --send-fixed-test")
        return preliminary
    if (args.network_approved is not True or
            args.second_confirmation is not True or
            args.approval_phrase != APPROVAL_PHRASE):
        raise PermissionError("All three explicit test-send authorizations required")
    consent=PrivateTestConsent(
        **config,
        authorization_phrase=args.approval_phrase,
        approved_until_unix_s=now+90,
    )
    # This call performs exactly 2 public HTTPS POSTs on an authorized
    # invocation: getChat and one sendMessage to a verified private chat.
    # Outcomes are not retried, including ambiguous HTTP outcomes.
    verified=optional_private_telegram_connectivity_test(
        consent,
        network_approved=True,
        second_operator_confirmed=True,
    )
    return {**verified,
            "production_strategy_restarted":False,
            "live_trade_signal_published":False}


def main():
    parser=argparse.ArgumentParser(
        description="V7Sonic PRIVATE bot preflight (NO NETWORK by default)"
    )
    parser.add_argument("--config",required=True,help="absolute private 0600 JSON path")
    parser.add_argument("--send-fixed-test",action="store_true")
    parser.add_argument("--network-approved",action="store_true")
    parser.add_argument("--second-confirmation",action="store_true")
    parser.add_argument("--approval-phrase",default=None)
    args=parser.parse_args()
    result=run_manual(args)
    print(json.dumps(result,sort_keys=True,indent=2))


if __name__=="__main__":
    main()
